// Copies the Lucide icons the UI uses into ../wwwroot/js/icons.js (inner SVG markup only).
import { readFileSync, writeFileSync } from 'node:fs';

const names = [
  'folder-open', 'save', 'save-all', 'chevron-left', 'chevron-right', 'chevrons-left', 'chevrons-right',
  'zoom-in', 'zoom-out', 'columns-3', 'rotate-cw', 'layers', 'scan-search', 'sliders-horizontal', 'upload',
  'notebook-pen', 'keyboard', 'trash-2', 'flag', 'eye', 'x', 'play', 'pause', 'square', 'folder',
  'external-link', 'sparkles', 'rotate-ccw', 'film', 'info', 'flip-horizontal-2', 'contrast', 'check-check',
  'scan', 'grid-2x2', 'history', 'crosshair', 'square-dashed-mouse-pointer',
];
const icons = {};
for (const n of names) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${n}.svg`, 'utf8');
  icons[n] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
const out = `// Generated by web-vendor/build-icons.mjs from lucide-static (ISC licence, https://lucide.dev).
// Do not edit by hand.
const ICONS = ${JSON.stringify(icons, null, 1)};

/** SVG markup for an icon. */
export function icon(name, size = 16) {
  const body = ICONS[name] || '';
  return \`<svg class="icon" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${body}</svg>\`;
}

/** Replaces every <i data-icon="name"> in root with its SVG. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('i[data-icon]')) {
    el.outerHTML = icon(el.dataset.icon, Number(el.dataset.size) || 16);
  }
}
`;
writeFileSync('../wwwroot/js/icons.js', out);
console.log(`wrote ${names.length} icons`);
